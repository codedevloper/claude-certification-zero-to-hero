#!/usr/bin/env python3
"""Build (or check) the objective coverage matrix for each supported track.

Inputs:
  16-certification-tracks/<slug>/objective-map.yaml   objective -> modules, labs
  17-practice-questions/<slug>/*.json                  questions (objective field)

Output:
  16-certification-tracks/<slug>/coverage-matrix.md

  python tools/build_coverage.py           # regenerate
  python tools/build_coverage.py --check   # fail on gaps or a stale matrix (CI)
"""
from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

import yaml

from common import ROOT, Report, certifications, load_questions


def link(from_dir: Path, target: str) -> str:
    rel = Path(*[".."] * len(from_dir.relative_to(ROOT).parts)) / target
    label = target.rstrip("/").split("/")[-1]
    if label.lower() in {"readme.md", ""}:
        label = target.rstrip("/").split("/")[-2]
    return f"[{label}]({rel.as_posix()})"


def build(cert: dict, report: Report) -> tuple[Path, str] | None:
    track_dir = ROOT / cert["track_dir"]
    map_path = track_dir / "objective-map.yaml"
    if not map_path.exists():
        report.error(f"{cert['code']}: missing {map_path.relative_to(ROOT)}")
        return None
    mapping = (yaml.safe_load(map_path.read_text(encoding="utf-8")) or {}).get("objectives", {})

    by_obj: dict[str, list[str]] = defaultdict(list)
    for q in load_questions(cert["slug"]):
        by_obj[q["objective"]].append(q["id"])

    lines = [
        f"# {cert['name']} ({cert['code']}) — Coverage Matrix",
        "",
        "> Generated by `tools/build_coverage.py` from `objective-map.yaml` and the question banks. Do not edit by hand.",
        f"> Objectives paraphrase the official exam guide v{cert['guide_version']} — see [registry.yaml](../registry.yaml) for sources.",
        "",
        "| Objective | Learning module(s) | Lab(s) | Practice questions |",
        "|---|---|---|---|",
    ]
    totals = {"objectives": 0, "covered": 0}
    for dom in cert["domains"]:
        lines.append(f"| **Domain {dom['id']} — {dom['name']} ({dom['weight']}%)** | | | |")
        for obj in dom["objectives"]:
            oid = obj["id"]
            entry = mapping.get(oid) or {}
            modules, labs = entry.get("modules", []), entry.get("labs", [])
            qs = sorted(by_obj.get(oid, []))
            totals["objectives"] += 1
            for p in modules + labs:
                if not (ROOT / p.split("#")[0]).exists():
                    report.error(f"{cert['code']} {oid}: mapped path does not exist: {p}")
            missing = [n for n, v in (("module", modules), ("lab", labs), ("question", qs)) if not v]
            if missing:
                report.error(f"{cert['code']} {oid}: no {', '.join(missing)} mapped")
            else:
                totals["covered"] += 1
            q_cell = f"{len(qs)}: " + ", ".join(qs[:6]) + (" …" if len(qs) > 6 else "") if qs else "—"
            lines.append(
                f"| {oid} {obj['text']} | {'<br>'.join(link(track_dir, m) for m in modules) or '—'} | "
                f"{'<br>'.join(link(track_dir, lab) for lab in labs) or '—'} | {q_cell} |"
            )
    extra = set(mapping) - {o["id"] for d in cert["domains"] for o in d["objectives"]}
    for oid in sorted(extra):
        report.error(f"{cert['code']}: objective-map.yaml lists unknown objective {oid}")
    lines += ["", f"**Fully covered objectives:** {totals['covered']} / {totals['objectives']}", ""]
    return track_dir / "coverage-matrix.md", "\n".join(lines)


def main(check: bool) -> int:
    report = Report("coverage matrix")
    for cert in certifications("supported"):
        result = build(cert, report)
        if not result:
            continue
        path, content = result
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                report.error(f"{path.relative_to(ROOT)} is stale — run python tools/build_coverage.py")
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    report.print()
    return 0 if report.ok else 1


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
