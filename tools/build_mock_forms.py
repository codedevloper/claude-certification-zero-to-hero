#!/usr/bin/env python3
"""Generate fixed mock-exam forms from the question banks.

Each supported track gets two full-length forms (official item count and time) that overlap
as little as the bank allows, plus one half-length form. Selection is blueprint-weighted
and deterministic, so forms only change when you regenerate them deliberately.

  python tools/build_mock_forms.py           # (re)generate forms
  python tools/build_mock_forms.py --check   # verify existing forms reference real questions
"""
from __future__ import annotations

import json
import random
import sys
from collections import defaultdict

from common import ROOT, Report, certifications, load_questions

sys.path.insert(0, str(ROOT / "18-mock-examinations" / "engine"))
from mockexam.selection import allocate  # noqa: E402

FORMS_DIR = ROOT / "18-mock-examinations" / "forms"
SEED = 20261024


def build_forms(cert: dict) -> list[dict]:
    rng = random.Random(f"{SEED}-{cert['code']}")
    by_domain: dict[int, list[str]] = defaultdict(list)
    for q in load_questions(cert["slug"]):
        by_domain[q["domain"]].append(q["id"])
    for ids in by_domain.values():
        ids.sort()
        rng.shuffle(ids)
    weights = {d["id"]: d["weight"] for d in cert["domains"] if by_domain.get(d["id"])}
    items, minutes = cert["format"]["items"], cert["format"]["minutes"]

    cursors = {d: 0 for d in by_domain}

    def take(count: int) -> list[str]:
        chosen: list[str] = []
        for d, n in allocate(weights, count).items():
            pool = by_domain[d]
            for _ in range(min(n, len(pool))):
                chosen.append(pool[cursors[d] % len(pool)])
                cursors[d] += 1
        return sorted(set(chosen))

    specs = [
        (1, "Full-length mock exam A", items, minutes),
        (2, "Full-length mock exam B", items, minutes),
        (3, "Half-length checkpoint", items // 2, minutes // 2),
    ]
    forms = []
    for n, title, count, mins in specs:
        ids = take(count)
        forms.append({
            "id": f"{cert['slug']}-form-{n}",
            "track": cert["code"],
            "title": f"{cert['code']} {title}",
            "items": len(ids),
            "minutes": mins,
            "unofficial": True,
            "note": "Generated by tools/build_mock_forms.py. Blueprint-weighted selection of unofficial practice questions.",
            "question_ids": ids,
        })
    return forms


def main(check: bool) -> int:
    report = Report("mock exam forms")
    FORMS_DIR.mkdir(parents=True, exist_ok=True)
    for cert in certifications("supported"):
        known = {q["id"] for q in load_questions(cert["slug"])}
        if not known:
            report.error(f"{cert['code']}: no questions to build forms from")
            continue
        if check:
            for path in sorted(FORMS_DIR.glob(f"{cert['slug']}-form-*.json")):
                form = json.loads(path.read_text(encoding="utf-8"))
                missing = [i for i in form["question_ids"] if i not in known]
                if missing:
                    report.error(f"{path.name}: unknown question IDs {missing[:5]}")
                if len(form["question_ids"]) != form["items"]:
                    report.error(f"{path.name}: items={form['items']} but {len(form['question_ids'])} IDs")
            if not list(FORMS_DIR.glob(f"{cert['slug']}-form-*.json")):
                report.error(f"{cert['code']}: no forms generated")
            continue
        for form in build_forms(cert):
            path = FORMS_DIR / f"{form['id']}.json"
            path.write_text(json.dumps(form, indent=2) + "\n", encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)} ({form['items']} items)")
    report.print()
    return 0 if report.ok else 1


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
